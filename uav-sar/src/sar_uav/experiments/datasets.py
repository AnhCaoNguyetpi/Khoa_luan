"""Synthetic SAR incident datasets.

Each incident = (IPP, find location, elapsed time, behaviour profile),
generated by the hidden ground-truth simulator -- the same generative
process stands in for ISRID-style incident records.  Training incidents
fit the data-driven belief model; test incidents evaluate prediction
quality (RQ1).
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Optional

import numpy as np

from ..config import deep_update, DEFAULT_CONFIG
from ..data.area import AreaData
from ..data.weather import make_weather
from ..sim.target import LostPersonSim, sample_profile
from ..utils.seed import spawn_rngs


@dataclass
class Incident:
    ipp: int
    find_cell: int
    elapsed_min: float
    profile: str


def generate_incidents(cfg: Dict, area: AreaData, n: int, seed: int,
                       profile_probs: Optional[Dict[str, float]] = None,
                       burn_range: Optional[List[int]] = None) -> List[Incident]:
    mcfg = deep_update(DEFAULT_CONFIG, cfg)
    probs = profile_probs or mcfg["target"]["profile_probs"]
    lo, hi = burn_range or mcfg["target"].get("burn_min_range", [30, 90])
    dt = float(mcfg["mission"]["dt_min"])
    children = np.random.SeedSequence(seed).spawn(n)
    trail_cells = np.flatnonzero(area.trail_mask.reshape(-1))
    pool = trail_cells if len(trail_cells) > 4 else area.land_idx()

    out: List[Incident] = []
    for i in range(n):
        rng_env, rng_target = [np.random.default_rng(s)
                               for s in children[i].spawn(2)]
        burn = float(rng_env.integers(int(lo), int(hi) + 1))
        prof = sample_profile(rng_target, probs)
        ipp = int(rng_env.choice(pool))
        weather = make_weather(burn + 2 * dt, dt, rng_env,
                               mcfg["weather"])
        rain_fn = lambda tick: float(weather.rain[min(int(tick), len(weather.rain) - 1)])
        sim = LostPersonSim(area, prof, ipp, rng_target,
                            moving=bool(mcfg["target"]["moving"]))
        path = sim.full_path(int(burn), 0.0, rain_fn)
        out.append(Incident(ipp=ipp, find_cell=int(path[-1]),
                            elapsed_min=burn, profile=prof))
    return out
